#!/usr/bin/env node
// Generates the site's data and pages from the release folder and the docs:
//
//   release folder (RELEASE_DIR, default site.config.json releaseDir):
//     RELEASE-NOTES.md, */BUILD-INFO-*.json, */SHA256SUMS*, archives,
//     pulsedepot/README.md + NEXUS.bbcode, crystalworkshop/ALPHA.md +
//     NEXUS.bbcode, mods/*/README.md + *.cws + THIRD-PARTY-NOTICES.txt
//   docs (DOCS_DIR, default ../docs): wiki/crystalworkshop/**, release/pulsedepot/**
//   licence (LICENSE_FILE, default ../LICENSE)
//
// Writes src/data/*.json, src/content/docs/{crystalworkshop,mods,pulsedepot}
// generated pages, src/assets/generated/**, public/legal/** and public/og/**,
// and the public repository's issue forms and labels under
// deploy-template/.github/ (one form option per published mod).
// Every source is optional: what is missing keeps the committed output, so the
// site still builds from a checkout without the release folder.
