/** Copies images to src/assets/generated/<set>/ (webp); a re-shot in src/assets/shots/<set>/ wins. */
function images(set, srcDir) {
  const out = path.join(GEN_ASSETS, set);
  const map = {};
  if (!existsSync(srcDir)) return map;
  mkdirSync(out, { recursive: true });
  const jobs = [];
  for (const f of readdirSync(srcDir)) {
    if (!/\.(png|jpe?g|webp)$/i.test(f)) continue;
    const stem = f.replace(/\.[^.]+$/, '');
    const shot = path.join(SHOTS, set, `${stem}.webp`);
    const dst = path.join(out, `${stem}.webp`);
    if (existsSync(shot)) {
      map[f] = shot;
      rmSync(dst, { force: true });
      continue;
    }
    map[f] = dst;
    if (!existsSync(dst) || statSync(dst).mtimeMs < statSync(path.join(srcDir, f)).mtimeMs) {
      jobs.push(sharp(path.join(srcDir, f)).webp({ quality: 90, effort: 6 }).toFile(dst));
    }
  }
  return Promise.all(jobs).then(() => map);
}

function imageRef(fromSlug, absFile) {
  const r = path.relative(path.dirname(fileOf(fromSlug)), absFile).split(path.sep).join('/');
  return r.startsWith('.') ? r : `./${r}`;
}

function convertWiki(md, slug, imgMap, opts = {}) {
  let body = md;
  body = body.replace(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g, (_, a, b) => {
    const label = b ? a : a;
    const target = WIKI_SLUG[(b || a).trim()];
    return target ? `[${label.trim()}](${rel(slug, target)})` : label;
  });
  body = body.replace(/\]\((?:\.\.\/)?wiki\/([\w-]+)\.md(#[\w-]+)?\)/g, (m, f, h) => {
    const target = WIKI.find(([n]) => n === f)?.[1];
    return target ? `](${rel(slug, target, h ? h.slice(1) : '')})` : m;
  });
  body = body.replace(/!\[([^\]]*)\]\((?:wiki\/)?images\/([^)]+)\)/g, (m, alt, f) => (imgMap[f] ? `![${alt}](${imageRef(slug, imgMap[f])})` : m));
  body = definitionLists(body);
  body = asides(body);
  body = siteLinks(sanitize(body), slug);
  body = escapeMdx(body);
  body = stepLists(body);
  body = osTabs(body);
  if (opts.dropRelated) body = body.replace(/\n## Related\n[\s\S]*?(?=\n## |$)/, '\n');
  return body.trim();
}

/** `](@/slug/#hash)` to a link relative to `slug`. */
function siteLinks(md, slug) {
  return md.replace(/\]\(@\/([^)#]*?)\/?(?:#([^)]*))?\)/g, (_, to, h) => `](${rel(slug, to, h || '')})`);
}

function frontmatter(fields) {
  const lines = ['---'];
  for (const [k, v] of Object.entries(fields)) {
    if (v === undefined) continue;
    if (typeof v === 'object') {
      lines.push(`${k}:`);
      for (const [k2, v2] of Object.entries(v)) {
        if (typeof v2 === 'object') {
          lines.push(`  ${k2}:`);
          for (const [k3, v3] of Object.entries(v2)) lines.push(`    ${k3}: ${yamlString(v3)}`);
        } else lines.push(`  ${k2}: ${yamlString(v2)}`);
      }
    } else lines.push(`${k}: ${yamlString(v)}`);
  }
  lines.push('---');
  return lines.join('\n');
}

