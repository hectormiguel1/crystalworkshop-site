// -------------------------------------------------------------- mod pages

function modPages(rel) {
  for (const m of rel.mods) {
    const slug = `mods/${m.id}`;
    // The README's Screenshots section (relative paths) becomes the site gallery.
    const sections = h2Sections(m.readme).filter((s) => s.title !== 'Changelog' && s.title !== 'Screenshots');
    const intro = sections[0].body;
    let body = sections
      .slice(1)
      .map((s) => `## ${s.title}\n\n${s.body}`)
      .join('\n\n');
    body = body.replace(/\n- Includes open-source components; their licences are listed in THIRD-PARTY-NOTICES\.txt\./, `\n- Includes open-source components; see [its third-party notices](${rel_(slug, 'legal/third-party')}).`);
    body = body.replace(/^(FINAL FANTASY XIII(?:-2)? is a trademark[^\n]*)$/m, '');
    let converted = stepLists(escapeMdx(sanitize(asides(`${intro}\n\n${body}`))), /^(Install|Using the mod)$/).trim();
    if (m.gallery?.length) {
      const shots = m.gallery.map((g) => `![${plainText(g.alt)}](${imageRef(slug, g.file)})\n_${plainText(g.caption)}_`).join('\n\n');
      // In-game screenshots right after the introduction (before Features).
      const at = converted.search(/^## /m);
      const block = `## Screenshots\n\n${shots}\n\n`;
      converted = at < 0 ? `${converted}\n\n${block}` : `${converted.slice(0, at)}${block}${converted.slice(at)}`;
    }
    const fm = {
      title: m.title,
      description: m.summary,
      sidebar: { label: m.name, badge: { text: m.games.map((g) => GAMES[g].short).join(' / '), variant: 'note' } },
    };
    write(
      fileOf(slug),
      `${frontmatter(fm)}\n${IMPORTS}\nimport ModHeader from '../../../components/ModHeader.astro';\nimport ChangelogList from '../../../components/ChangelogList.astro';\n\n${GENERATED}\n\n<ModHeader id="${m.id}" />\n\n${converted}\n\n## Changelog\n\n<ChangelogList product="${m.id}" />\n`,
    );
  }
  log(`wrote ${rel.mods.length} mod pages`);
}

