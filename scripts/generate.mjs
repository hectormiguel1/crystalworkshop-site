function stageOf(version) {
  if (/-alpha/.test(version)) return 'alpha';
  if (/-beta/.test(version)) return 'beta';
  return 'release';
}

function gamesIn(text) {
  const out = [];
  if (/FINAL FANTASY XIII(?!-2)\b(?!-)/.test(text.replace(/FINAL FANTASY XIII-2/g, ''))) out.push('xiii');
  if (/XIII-2/.test(text)) out.push('xiii2');
  if (/LIGHTNING RETURNS/.test(text)) out.push('lr');
  return out;
}

function sha256sums(file) {
  const out = {};
  if (!existsSync(file)) return out;
  for (const line of read(file).split('\n')) {
    const m = line.match(/^([0-9a-f]{64})\s+\*?(.+)$/);
    if (m) out[path.basename(m[2].trim())] = m[1];
  }
  return out;
}

function bbSummary(bb) {
  const m = bb.match(/^\[size=3\]([\s\S]*?)\[\/size\]/m);
  return m ? m[1].trim() : '';
}

/** Splits "first public release. A, B and C." into a title and items. */
function changelogItems(text) {
  const [head, ...rest] = text.split(/\.\s+/);
  const tail = rest.join('. ').replace(/\.$/, '');
  const items = tail ? tail.split(/,\s+(?![^()]*\))/).map((s) => (/^\S*\./.test(s) ? s : s.charAt(0).toUpperCase() + s.slice(1))) : [];
  return { title: head.charAt(0).toUpperCase() + head.slice(1).replace(/\.$/, ''), items };
}

// ---------------------------------------------------------------- releases

function requirementRows(notes) {
  const sec = h2Sections(notes).find((s) => s.title === 'Requirements');
  const rows = {};
  if (!sec) return rows;
  for (const [label, windows, linux] of parseTable(sec.body).rows) rows[label] = { windows, linux };
  return rows;
}

function knownIssues(notes) {
  const sec = h2Sections(notes).find((s) => s.title === 'Known issues');
  if (!sec) return [];
  return sec.body
    .split(/\n(?=- )/)
    .map((s) => s.replace(/^- /, '').replace(/\s*\n\s*/g, ' ').trim())
    .filter(Boolean);
}

function appRelease(dir, id, name, opts) {
  const base = path.join(RELEASE, dir);
  if (!existsSync(base)) return null;
  const info = (os) => JSON.parse(read(path.join(base, `BUILD-INFO-${os}.json`)));
  const win = info('windows');
  const sums = sha256sums(path.join(base, 'SHA256SUMS.txt'));
  const asset = (os, ext) => {
    const file = `${win.package.replace(/-windows-x86_64$/, '')}-${os}-x86_64.${ext}`;
    return { file, bytes: statSync(path.join(base, file)).size, sha256: sums[file] };
  };
  const nexus = read(path.join(base, 'NEXUS.bbcode'));
  const reqs = (os) => opts.reqRows.filter((r) => opts.rows[r]).map((r) => `**${r}:** ${opts.rows[r][os]}`);
  const version = win.version;
  return {
    id,
    name,
    kind: 'app',
    version,
    stage: stageOf(version),
    date: win.verification?.date || opts.date,
    games: ['xiii', 'xiii2', 'lr'],
    stores: appStores(id),
    summary: bbSummary(nexus),
    tag: config.tagPattern.replace('{id}', id).replace('{version}', version),
    docs: opts.docs,
    icon: id,
    contents: opts.contents,
    features: bbList(nexus, opts.featuresHeading),
    platforms: {
      windows: { ...asset('windows', 'zip'), requirements: reqs('windows'), label: 'Windows 10/11 x64' },
      linux: { ...asset('linux', 'zip'), requirements: reqs('linux'), label: 'Linux x86_64' },
    },
    changelog: bbChangelog(nexus),
    knownIssues: bbList(nexus, 'Known issues'),
  };
}

function cruxRelease(pulsedepot, rows) {
  const archive = path.join(RELEASE, 'pulsedepot', pulsedepot.platforms.linux.file);
  const raw = existsSync(archive) ? readFromZip(archive, 'Crux/CRUX-MANIFEST.json') : null;
  if (!raw) return null;
  const manifest = JSON.parse(raw.toString('utf8'));
  const builds = Object.entries(manifest.files).map(([file, f]) => ({
    file,
    variant: f.variant,
    bytes: f.bytes,
    sha256: f.sha256,
    install: manifest.install?.[f.variant] || '',
  }));
  const game = rows['The game'] || { windows: '', linux: '' };
  const platform = (os) => ({
    ...pulsedepot.platforms[os],
    requirements: [
      `**Installed by PulseDepot** ${pulsedepot.version}: it checks each DLL's SHA-256 before installing it.`,
      `**The game:** ${game[os]}`,
    ],
  });
  return {
    id: 'crux',
    name: 'Crux',
    kind: 'component',
    version: pulsedepot.version,
    stage: pulsedepot.stage,
    date: pulsedepot.date,
    games: ['xiii', 'xiii2', 'lr'],
    stores: appStores('crux'),
    summary: 'The mod host the game loads. It serves the merged mod image to the game while it runs and loads the mods’ native code. It ships inside PulseDepot, which installs the right build for you.',
    tag: pulsedepot.tag,
    bundledWith: 'pulsedepot',
    docs: 'crux',
    icon: 'crux',
    builds,
    platforms: { windows: platform('windows'), linux: platform('linux') },
    changelog: [
      {
        version: pulsedepot.version,
        text: `First public release, bundled with PulseDepot ${pulsedepot.version}. ${builds
          .map((b) => `${b.file} (${b.variant === 'addon' ? 'NovaFix addon' : 'standalone'})`)
          .join(', ')}, SHA-256 verified by PulseDepot before install.`,
      },
    ],
  };
}

/**
 * A mod's in-game screenshots (`mods/<slug>/screenshots/manifest.json`):
 * the 1600 px WebP goes to src/assets/generated/mods/<slug>/ (the page
 * gallery, lightbox), the thumbnail to public/shots/mods/<slug>/ (the mod
 * card). Featured images first, as the manifest orders them.
 */
function modShots(slug, dir) {
  const file = path.join(dir, 'screenshots', 'manifest.json');
  if (!existsSync(file)) return { screenshots: [], gallery: [] };
  const list = JSON.parse(read(file)).images || [];
  const gen = path.join(GEN_ASSETS, 'mods', slug);
  const pub = path.join(PUBLIC, 'shots', 'mods', slug);
  rmSync(gen, { recursive: true, force: true });
  rmSync(pub, { recursive: true, force: true });
  mkdirSync(gen, { recursive: true });
  mkdirSync(pub, { recursive: true });
  const screenshots = [];
  const gallery = [];
  for (const i of list) {
    copyFileSync(path.join(dir, 'screenshots', i.webp), path.join(gen, i.webp));
    copyFileSync(path.join(dir, 'screenshots', i.thumb), path.join(pub, i.thumb));
    screenshots.push({ id: i.id, caption: i.caption, alt: i.alt, featured: !!i.featured, thumb: `shots/mods/${slug}/${i.thumb}` });
    gallery.push({ caption: i.caption, alt: i.alt, file: path.join(gen, i.webp) });
  }
  return { screenshots, gallery };
}

/** MDX-safe text for an image's alt or caption. */
function plainText(s) {
  return s.replace(/[{}<>[\]*_`\\]/g, ' ').replace(/\s+/g, ' ').trim();
}

function modReleases(names, date) {
  const base = path.join(RELEASE, 'mods');
  if (!existsSync(base)) return [];
  const sums = sha256sums(path.join(base, 'SHA256SUMS'));
  const out = [];
  for (const slug of readdirSync(base).filter((d) => statSync(path.join(base, d)).isDirectory()).sort()) {
    const dir = path.join(base, slug);
    const readme = read(path.join(dir, 'README.md'));
    const { title: h1, body } = takeTitle(readme);
    const version = (h1.match(/(\d+\.\d+\.\d+(?:-[\w.]+)?)\s*$/) || [])[1] || '0.0.0';
    const title = h1.replace(/\s+\d+\.\d+\.\d+(?:-[\w.]+)?\s*$/, '').trim();
    const file = readdirSync(dir).find((f) => f.endsWith('.cws'));
    const sections = h2Sections(body);
    const req = sections.find((s) => s.title === 'Requirements')?.body || '';
    const games = gamesIn(req.split('\n')[0] || title);
    const changelog = sections.find((s) => s.title === 'Changelog')?.body || '';
    const entries = [...changelog.matchAll(/^###\s+(\S+)\s*[–-]?\s*(.*)\n([\s\S]*?)(?=^###\s|(?![\s\S]))/gm)].map((m) => ({
      version: m[1],
      title: m[2].trim() ? m[2].trim().charAt(0).toUpperCase() + m[2].trim().slice(1) : '',
      items: m[3]
        .split('\n')
        .filter((l) => l.startsWith('- '))
        .map((l) => l.slice(2).trim()),
    }));
    const requires = ['pulsedepot', 'crux'];
    const needsSettings = /Mod Settings\*\*\s+\d/.test(req);
    if (needsSettings) requires.push('mod-settings');
    const short = names[`mods/${slug}/${file}`] || title;
    const asset = { file, bytes: statSync(path.join(dir, file)).size, sha256: sums[`${slug}/${file}`] || sums[file] };
    const reqItems = req
      .split('\n')
      .filter((l) => l.startsWith('- '))
      .map((l) => sanitize(l.slice(2)));
    const stores = modStores(reqItems);
    const { screenshots, gallery } = modShots(slug, dir);
    out.push({
      id: slug,
      name: short,
      title,
      kind: 'mod',
      version,
      stage: stageOf(version),
      date,
      games,
      stores,
      summary: firstParagraph(body),
      tag: config.tagPattern.replace('{id}', slug).replace('{version}', version),
      docs: `mods/${slug}`,
      icon: 'shard',
      requires,
      platforms: {
        windows: { ...asset, requirements: reqItems, label: 'Windows' },
        linux: {
          ...asset,
          requirements: [
            ...reqItems,
            '**Proton:** without NovaFix, the game’s Steam launch options need `WINEDLLOVERRIDES="version=n,b" %command%` so Crux loads.',
          ],
          label: 'Linux (Proton)',
        },
      },
      changelogEntries: entries,
      readme: body,
      screenshots,
      gallery,
    });
  }
  return out;
}

function releases() {
  if (!existsSync(path.join(RELEASE, 'RELEASE-NOTES.md'))) {
    log(`no release folder at ${path.relative(SITE, RELEASE)}: keeping the committed release data`);
    return null;
  }
  const notes = read(path.join(RELEASE, 'RELEASE-NOTES.md'));
  const date = (path.basename(RELEASE).match(/(\d{4}-\d{2}-\d{2})/) || [])[1] || '';
  const rows = requirementRows(notes);
  const modsTable = parseTable(h2Sections(notes).find((s) => s.title === 'Mods')?.body || '');
  const names = Object.fromEntries(modsTable.rows.map(([name, shard]) => [shard.replace(/`/g, ''), name]));
  const pulsedepot = appRelease('pulsedepot', 'pulsedepot', 'PulseDepot', {
    rows,
    date,
    reqRows: ['PulseDepot', 'The game', 'Script mods and script editing'],
    docs: 'pulsedepot',
    featuresHeading: 'Features',
    contents: ['PulseDepot', 'Crux (NovaFix addon and standalone builds)', 'Vineflower 1.12.0 (for script mods)', 'Guide with screenshots'],
  });
  const crystalworkshop = appRelease('crystalworkshop', 'crystalworkshop', 'CrystalWorkshop', {
    rows,
    date,
    reqRows: ['CrystalWorkshop previews', 'Script mods and script editing'],
    docs: 'crystalworkshop',
    featuresHeading: 'What you can do',
    contents: ['CrystalWorkshop (editor)', 'crystalw (command line and MCP server)', 'PulseDepot', 'Vineflower 1.12.0', 'DXVK 3.1.1 (Windows package)', 'Wiki guides'],
  });
  const crux = pulsedepot ? cruxRelease(pulsedepot, rows) : null;
  const mods = modReleases(names, date);
  return { date, notes, products: [crystalworkshop, pulsedepot, crux].filter(Boolean), mods, knownIssues: knownIssues(notes) };
}

function changelogData(rel) {
  const entries = [];
  for (const p of rel.products) {
    for (const c of p.changelog || []) {
      const { title, items } = changelogItems(c.text);
      const extra = p.id === 'crystalworkshop' && items.length === 0 ? p.features.map((f) => f.replace(/:.*$/, '')) : [];
      entries.push({ product: p.id, name: p.name, kind: p.kind, games: p.games, version: c.version, stage: stageOf(c.version), date: p.date, title, items: [...items, ...extra] });
    }
  }
  for (const m of rel.mods) {
    for (const c of m.changelogEntries) {
      entries.push({ product: m.id, name: m.name, kind: 'mod', games: m.games, version: c.version, stage: stageOf(c.version), date: m.date, title: c.title || 'Release', items: c.items });
    }
  }
  return entries.map((e) => ({ ...e, id: `${e.product}-${e.version}`.replace(/[^\w.-]/g, '-'), items: e.items.map(inlineHtml) }));
}

// ----------------------------------------------------------- notices

function parseNotices(file) {
  const lines = read(file).split('\n');
  const stop = lines.findIndex((l) => l.trim() === 'Licence texts');
  const out = [];
  let group = '';
  for (let i = 0; i < (stop < 0 ? lines.length : stop); i++) {
    const l = lines[i];
    if (/^=+$/.test(l) && lines[i + 2] && /^=+$/.test(lines[i + 2])) {
      group = lines[i + 1].trim();
      i += 2;
      continue;
    }
    if (!group || !l || l.startsWith(' ') || !lines[i + 1]?.startsWith('  ')) continue;
    const entry = { name: l.trim(), group, licence: '', copyright: '', source: '' };
    while (lines[i + 1]?.startsWith('  ')) {
      const t = lines[++i].trim();
      if (/^Copyright\b/i.test(t) && !/^Copyright:/i.test(t)) {
        entry.copyright = t;
        continue;
      }
      const m = t.match(/^([A-Za-z ]+):\s*(.*)$/);
      if (!m) continue;
      const key = m[1].toLowerCase();
      if (key === 'licence') entry.licence = m[2];
      else if (key === 'copyright') entry.copyright = m[2];
      else if (key === 'source') entry.source = m[2];
    }
    out.push(entry);
  }
  return out;
}

function notices() {
  const packages = [
    ['crystalworkshop', 'windows'],
    ['crystalworkshop', 'linux'],
    ['pulsedepot', 'windows'],
    ['pulsedepot', 'linux'],
  ];
  const found = packages.filter(([p, os]) => existsSync(path.join(RELEASE, p, `THIRD-PARTY-NOTICES-${os}.txt`)));
  if (!found.length) return null;
  const merged = new Map();
  const files = [];
  for (const [p, os] of found) {
    const src = path.join(RELEASE, p, `THIRD-PARTY-NOTICES-${os}.txt`);
    const name = `${p}-${os}.txt`;
    copyFileSync(src, path.join(PUBLIC, 'legal', name));
    files.push({ product: p, os, file: `legal/${name}` });
    for (const e of parseNotices(src)) {
      const key = `${e.name}|${e.licence}`;
      const cur = merged.get(key) || { ...e, packages: [] };
      cur.packages.push(`${p}-${os}`);
      merged.set(key, cur);
    }
  }
  const mods = [];
  const modBase = path.join(RELEASE, 'mods');
  if (existsSync(modBase)) {
    for (const slug of readdirSync(modBase)) {
      const src = path.join(modBase, slug, 'THIRD-PARTY-NOTICES.txt');
      if (!existsSync(src)) continue;
      copyFileSync(src, path.join(PUBLIC, 'legal', `mod-${slug}.txt`));
      mods.push({ mod: slug, file: `legal/mod-${slug}.txt` });
    }
  }
  return { files, mods, components: [...merged.values()].sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' })) };
}

