function featureMatrix() {
  const file = existsSync(path.join(RELEASE, 'crystalworkshop/ALPHA.md'))
    ? path.join(RELEASE, 'crystalworkshop/ALPHA.md')
    : path.join(DOCS, 'release/crystalworkshop/ALPHA.md');
  if (!existsSync(file)) return null;
  const md = read(file);
  const rows = [];
  const status = h2Sections(md).find((s) => s.title === 'Feature status');
  if (!status) return null;
  const legend = status.body.split(/\n###\s/)[0].trim();
  for (const block of status.body.split(/\n(?=###\s)/).slice(1)) {
    const heading = block.match(/^###\s+(.+)$/m)[1].trim();
    const game = heading.includes('XIII-2') ? 'xiii2' : heading.includes('LIGHTNING') ? 'lr' : 'xiii';
    for (const [area, completed, experimental, gaps] of parseTable(block).rows) {
      const cell = (s) => (s && s !== '—' ? inlineHtml(s) : '');
      rows.push({ game, area: area.replace(/\*\*/g, ''), completed: cell(completed), experimental: cell(experimental), gaps: cell(gaps) });
    }
  }
  return { legend: inlineHtml(plainLegend(legend)), rows };
}

function plainLegend(s) {
  return s.replace(/\s*\n\s*/g, ' ');
}

