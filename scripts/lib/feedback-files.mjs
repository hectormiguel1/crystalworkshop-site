// Renders the feedback files of the public repository (issue forms, the
// template chooser config and labels.yml) as YAML text, keyed by their path
// under .github/. Used by scripts/generate.mjs (writes them) and
// scripts/check-issue-forms.mjs (checks they are current).
import { stringify } from 'yaml';
import { issueConfig, issueForms, labels } from './feedback.mjs';

const HEAD = '# Generated by scripts/generate.mjs from the release data (npm run generate). Do not edit by hand.\n';
const yaml = (v) => HEAD + stringify(v, { lineWidth: 0 });

export function renderFeedbackFiles(releases, config) {
  const out = {};
  for (const [file, form] of Object.entries(issueForms(releases, config))) out[`ISSUE_TEMPLATE/${file}`] = yaml(form);
  out['ISSUE_TEMPLATE/config.yml'] = yaml(issueConfig(config));
  out['labels.yml'] = yaml(labels(releases));
  return out;
}
